const FALLBACK = FONT["?"];

/** Wandelt Text in die zeichenbare Form: Großbuchstaben, ß wird zu SS. */
export function normalize(text: string): string {
  return text.replace(/ß/g, "ss").toUpperCase();
}

export function glyphFor(ch: string): string[] {
  return FONT[ch] ?? FALLBACK;
}

/** Breite eines Textes in Schriftpixeln, ohne Skalierung. */
export function measure(text: string): number {
  const n = normalize(text).length;
  return n === 0 ? 0 : n * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP;
}

/**
 * Zeichnet Text ins Canvas. Die Koordinaten sind bereits skalierte Pixel.
 * Es wird bewusst mit fillRect gearbeitet - kein Kantenglätten, keine
 * Zwischentöne.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: string,
): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of normalize(text)) {
    const glyph = glyphFor(ch);
    for (let row = 0; row < GLYPH_H; row++) {
      const line = glyph[row];
      for (let col = 0; col < GLYPH_W; col++) {
        if (line[col] === "#") {
          ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    cx += (GLYPH_W + GLYPH_GAP) * scale;
  }
}
